////////////////////////////////////////
// 定时器0初始化函数
// 入口参数: 无
// 函数返回: 无
////////////////////////////////////////
void TIMER0_Init(u16 us) //us:1~1638
{
	u16 cnt;

	if(us > 1638) us = 1638;
	cnt = (u16)(SYSCLK / 1000000UL * us);

    CLR_REG_BIT(TMOD, BIT2);	//设置定时器0为定时模式
    SET_REG_BIT(AUXR, BIT7);	//设置定时器0为1T模式
    MODIFY_REG(TMOD, BIT1 | BIT0, ((0) << 0));	//设置定时器0为模式0 (16位自动重载模式)
    CLR_REG_BIT(TMOD, BIT3);           //禁止定时器0门控
    PT0 = ((0) & 1);MODIFY_REG(IPH, BIT1, ((((0) >> 1) & 1) << 1));	//设置中断为最低优先级
    ET0 = 1;					//使能定时器0中断
	TH0 = (65536 - cnt) >> 8;	//设置定时器0的16位重载值
	TL0 = (65536 - cnt) & 0xFF;
    TR0 = 1;					//定时器0开始运行
}


